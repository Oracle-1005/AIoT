live_loop :music_beat_reporter do
  wait_until_playing
  use_bpm get(:current_bpm).to_f
  beat_count = get(:beat_count).to_i
  beat_number = (beat_count % 4) + 1
  bar_number = beat_count / 4
  strength = beat_number == 1 ? 1.0 : 0.45
  osc "/music/beat", bar_number, beat_number, get(:current_bpm).to_f, strength
  if beat_number == 1
    set :bar_count, bar_number
    osc "/music/bar", bar_number, "faded"
  end
  set :beat_count, (beat_count + 1) % 312
  wait_music_beats 1.0
end

