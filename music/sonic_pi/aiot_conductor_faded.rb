define :play_voice_event do |role, note_value, duration, velocity|
  config = voice_config role
  synth_name, role_amp, release_scale, transpose, pan_value = config
  release_value = [[duration.to_f * release_scale.to_f, 0.08].max, 8.0].min
  use_synth synth_name
  amp_value = clamp_value(velocity, 0.05, 1.0) * role_amp.to_f * get(:master_amp).to_f
  play note_value.to_i + transpose.to_i,
       attack: 0.01,
       release: release_value,
       amp: amp_value,
       pan: pan_value.to_f
end

define :play_drum_event do |note_value, velocity|
  style = get(:current_style)
  midi_note = note_value.to_i
  allowed = true
  sample_name = :sn_dub

  if [35, 36].include?(midi_note)
    sample_name = :bd_haus
  elsif [37, 38, 39, 40].include?(midi_note)
    sample_name = :sn_dub
  elsif [42, 44, 51, 53, 59].include?(midi_note)
    sample_name = :drum_cymbal_closed
  elsif [46, 49, 52, 55, 57].include?(midi_note)
    sample_name = :drum_cymbal_open
  else
    sample_name = :sn_dub
  end

  if style == :piano_ballad
    allowed = [35, 36, 38, 40, 49, 57].include?(midi_note)
    style_amp = 0.22
    cutoff_value = 95
  elsif style == :festival
    style_amp = 0.58
    cutoff_value = 125
  else
    style_amp = 0.38
    cutoff_value = 112
  end

  if allowed
    amp_value = clamp_value(velocity, 0.05, 1.0) * style_amp * get(:master_amp).to_f
    sample sample_name, amp: amp_value, cutoff: cutoff_value
  end
end

define :perform_event_track do |events, role, total_beats|
  cursor = 0.0
  events.each do |event|
    start_beat, duration, note_value, velocity = event
    wait_music_beats start_beat.to_f - cursor
    wait_until_playing
    if layer_enabled_for_role role
      if role == :drums
        play_drum_event note_value, velocity
      else
        play_voice_event role, note_value, duration, velocity
      end
    end
    cursor = start_beat.to_f
  end
  wait_music_beats total_beats.to_f - cursor
end

