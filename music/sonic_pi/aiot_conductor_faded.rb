define :clamp_value do |value, low, high|
  [[value.to_f, low].max, high].min
end

define :approach_value do |current, target, amount|
  current.to_f + ((target.to_f - current.to_f) * amount.to_f)
end

define :wait_until_playing do
  while get(:playing) != true
    sleep 0.05
  end
end

define :wait_music_beats do |beats|
  remaining = [beats.to_f, 0.0].max
  while remaining > 0.0001
    if get(:playing) == true
      use_bpm get(:current_bpm).to_f
      step = [remaining, 0.125].min
      sleep step
      remaining = remaining - step
    else
      sleep 0.05
    end
  end
end

define :layer_enabled_for_role do |role|
  if [:melody, :lead].include?(role)
    get(:layer_melody) == true
  elsif [:harmony, :pad].include?(role)
    get(:layer_harmony) == true
  elsif role == :bass
    get(:layer_bass) == true
  else
    get(:layer_rhythm) == true
  end
end

